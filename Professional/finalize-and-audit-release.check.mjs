import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import bitcoin from 'bitcoinjs-lib';
import {secp256k1} from '@noble/curves/secp256k1';
import {finalizeAndAuditProfessionalRelease} from './finalize-and-audit-release.mjs';
const secret=Buffer.alloc(32);secret[31]=9;
const pub=Buffer.from(secp256k1.getPublicKey(secret,true));
const redeem=bitcoin.script.compile([bitcoin.script.number.encode(110),bitcoin.opcodes.OP_CHECKLOCKTIMEVERIFY,bitcoin.opcodes.OP_DROP,pub,bitcoin.opcodes.OP_CHECKSIG]);
const payment=bitcoin.payments.p2sh({redeem:{output:redeem},network:bitcoin.networks.regtest});
const prev=new bitcoin.Transaction();prev.version=2;prev.addInput(Buffer.alloc(32,1),0);prev.addOutput(payment.output,100000);
const dest=Buffer.from('0014'+'bb'.repeat(20),'hex');
const psbt=new bitcoin.Psbt({network:bitcoin.networks.regtest});
psbt.setVersion(2);psbt.setLocktime(110);
psbt.addInput({hash:prev.getId(),index:0,sequence:0xfffffffe,nonWitnessUtxo:prev.toBuffer(),redeemScript:redeem});
psbt.addOutput({script:dest,value:99000});
const original=psbt.toBase64(),digest=createHash('sha256').update(Buffer.from(original,'base64')).digest('hex');
const tx=bitcoin.Transaction.fromBuffer(psbt.data.globalMap.unsignedTx.toBuffer());
const hash=tx.hashForSignature(0,redeem,bitcoin.Transaction.SIGHASH_ALL);
const signature=bitcoin.script.signature.encode(Buffer.from(secp256k1.sign(hash,secret,{lowS:true}).toCompactRawBytes()),bitcoin.Transaction.SIGHASH_ALL);
const signed=bitcoin.Psbt.fromBase64(original);
signed.updateInput(0,{partialSig:[{pubkey:pub,signature}]});
const approval={fundingTxid:prev.getId(),fundingVout:0,inputSats:100000,destinationScriptHex:dest.toString('hex'),payoutSats:99000,locktime:110,signerPubkeyHex:pub.toString('hex'),redeemScriptHex:redeem.toString('hex')};
const result=finalizeAndAuditProfessionalRelease(original,signed.toBase64(),digest,approval);
assert.equal(result.independentFinalAuditPassed,true);
assert.equal(result.finalized,true);
assert.equal(result.broadcast,false);
assert.equal(result.feeSats,1000);
assert.throws(()=>finalizeAndAuditProfessionalRelease(original,signed.toBase64(),digest,{...approval,payoutSats:98000}),/Final destination or payout mismatch/);
assert.throws(()=>finalizeAndAuditProfessionalRelease(original,signed.toBase64(),digest,{...approval,locktime:111}),/Final CLTV locktime or sequence mismatch/);
assert.throws(()=>finalizeAndAuditProfessionalRelease(original,signed.toBase64(),digest,{...approval,signerPubkeyHex:'02'+'11'.repeat(32)}),/Final signer or CLTV script mismatch/);
assert.throws(()=>finalizeAndAuditProfessionalRelease(original,signed.toBase64(),digest),/Independent transaction approval record required/);
assert.throws(()=>finalizeAndAuditProfessionalRelease(original,original,digest,approval),/no signing material/);
console.log('PASS: controlled finalization requires independent raw transaction audit; mismatched approval fails closed; no broadcast');
