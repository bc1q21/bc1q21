import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import bitcoin from 'bitcoinjs-lib';
import { releaseExactlyApprovedUnsignedPsbt } from './approved-psbt-handoff.mjs';
const tx=new bitcoin.Transaction();tx.version=2;tx.addInput(Buffer.alloc(32,1),0,0xfffffffe);tx.addOutput(Buffer.from('0014'+'aa'.repeat(20),'hex'),99000);
const psbt=new bitcoin.Psbt({network:bitcoin.networks.regtest});
psbt.addInput({hash:tx.getId(),index:0,sequence:0xfffffffe,nonWitnessUtxo:tx.toBuffer()});
psbt.addOutput({script:Buffer.from('0014'+'bb'.repeat(20),'hex'),value:98000});
const b64=psbt.toBase64();
const digest=createHash('sha256').update(Buffer.from(b64,'base64')).digest('hex');
const release={network:'regtest',unsignedPsbtBase64:b64,signed:false,broadcast:false};
const approval={network:'regtest',psbtSha256:digest,explicitlyApproved:true,signed:false,broadcast:false};
const good=releaseExactlyApprovedUnsignedPsbt(release,approval);
assert.equal(good.psbtSha256,digest);assert.equal(good.unsignedPsbtBase64,b64);
assert.equal(good.signed,false);assert.equal(good.broadcast,false);
assert.throws(()=>releaseExactlyApprovedUnsignedPsbt(release,{...approval,explicitlyApproved:false}),/Explicit unsigned regtest approval/);
assert.throws(()=>releaseExactlyApprovedUnsignedPsbt(release,{...approval,psbtSha256:'00'.repeat(32)}),/PSBT changed after approval/);
assert.throws(()=>releaseExactlyApprovedUnsignedPsbt({...release,network:'bitcoin'},approval),/Explicit unsigned regtest approval/);
assert.throws(()=>releaseExactlyApprovedUnsignedPsbt({...release,unsignedPsbtBase64:'bad'},approval),/Invalid PSBT encoding/);
const altered=bitcoin.Psbt.fromBase64(b64);
altered.addUnknownKeyValToOutput(0,{key:Buffer.from('fc01','hex'),value:Buffer.from('01','hex')});
assert.notEqual(altered.toBase64(),b64,'Tamper fixture must actually change serialized PSBT bytes');
assert.throws(()=>releaseExactlyApprovedUnsignedPsbt({...release,unsignedPsbtBase64:altered.toBase64()},approval),/PSBT changed after approval/);
console.log('PASS: exact approved PSBT bytes only; altered PSBT and absent approval fail closed');
