const view=viewHistoricalProfessionalGift(url,proof);
assert.equal(view.giftAddress,proof.giftLinkFundingAddress);
assert.equal(view.fundingTxid,proof.fundingTxid);
assert.equal(view.releaseCount,24);
assert.equal(view.totalScheduledSats,564000);
assert.equal(view.releases[0].sats,12000);
assert.equal(view.releases[23].sats,35000);
assert.ok(view.releases.every(r=>r.date===null&&!r.maturityVerified&&!r.confirmedUnspent));
