import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import bitcoin from 'bitcoinjs-lib';
import {secp256k1} from '@noble/curves/secp256k1';
import {verifyProfessionalReturnedSignature} from './verify-returned-signature.mjs';
const secret=Buffer.alloc(32);secret[31]=9;
const pub=Buffer.from(secp256k1.getPublicKey(secret,true));
const redeem=bitcoin.script.compile([bitcoin.script.number.encode(110),bitcoin.opcodes.OP_CHECKLOCKTIMEVERIFY,bitcoin.opcodes.OP_DROP,pub,bitcoin.opcodes.OP_CHECKSIG]);
const payment=bitcoin.payments.p2sh({redeem:{output:redeem},network:bitcoin.networks.regtest});
const prev=new bitcoin.Transaction();prev.version=2;prev.addInput(Buffer.alloc(32,1),0);prev.addOutput(payment.output,100000);
const psbt=new bitcoin.Psbt({network:bitcoin.networks.regtest});
psbt.setVersion(2);psbt.setLocktime(110);
psbt.addInput({hash:prev.getId(),index:0,sequence:0xfffffffe,nonWitnessUtxo:prev.toBuffer(),redeemScript:redeem});
psbt.addOutput({script:Buffer.from('0014'+'bb'.repeat(20),'hex'),value:99000});
const original=psbt.toBase64(),digest=createHash('sha256').update(Buffer.from(original,'base64')).digest('hex');
const tx=bitcoin.Transaction.fromBuffer(psbt.data.globalMap.unsignedTx.toBuffer());
const hash=tx.hashForSignature(0,redeem,bitcoin.Transaction.SIGHASH_ALL);
const der=Buffer.from(secp256k1.sign(hash,secret,{lowS:true}).toCompactRawBytes());
const signed=bitcoin.Psbt.fromBase64(original);
signed.updateInput(0,{partialSig:[{pubkey:pub,signature:bitcoin.script.signature.encode(der,bitcoin.Transaction.SIGHASH_ALL)}]});
const result=verifyProfessionalReturnedSignature(original,signed.toBase64(),digest);
assert.equal(result.signatureCryptographicallyVerified,true);
assert.equal(result.finalized,false);assert.equal(result.broadcast,false);
const wrong=bitcoin.Psbt.fromBase64(original);
const wrongHash=Buffer.from(hash);wrongHash[0]^=1;
const wrongDer=Buffer.from(secp256k1.sign(wrongHash,secret,{lowS:true}).toCompactRawBytes());
wrong.updateInput(0,{partialSig:[{pubkey:pub,signature:bitcoin.script.signature.encode(wrongDer,bitcoin.Transaction.SIGHASH_ALL)}]});
assert.throws(()=>verifyProfessionalReturnedSignature(original,wrong.toBase64(),digest),/Invalid Bitcoin transaction signature/);
assert.throws(()=>verifyProfessionalReturnedSignature(original,original,digest),/no signing material/);
const permissive=bitcoin.Psbt.fromBase64(original);
const permissiveHash=tx.hashForSignature(0,redeem,bitcoin.Transaction.SIGHASH_NONE);
const permissiveSig=Buffer.from(secp256k1.sign(permissiveHash,secret,{lowS:true}).toCompactRawBytes());
permissive.updateInput(0,{partialSig:[{pubkey:pub,signature:bitcoin.script.signature.encode(permissiveSig,bitcoin.Transaction.SIGHASH_NONE)}]});
assert.throws(()=>verifyProfessionalReturnedSignature(original,permissive.toBase64(),digest),/Only SIGHASH_ALL is permitted/);
const inconsistent=bitcoin.Psbt.fromBase64(signed.toBase64());
inconsistent.updateInput(0,{sighashType:bitcoin.Transaction.SIGHASH_NONE});
assert.throws(()=>verifyProfessionalReturnedSignature(original,inconsistent.toBase64(),digest),/Returned sighash metadata differs from approved PSBT/);
console.log('PASS: valid synthetic CLTV ECDSA signature accepted, incorrect signature rejected; no finalize/broadcast');
