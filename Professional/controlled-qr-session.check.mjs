import assert from 'node:assert/strict';
import { URDecoder } from '@ngraveio/bc-ur';
import bitcoin from 'bitcoinjs-lib';
import { secp256k1 } from '@noble/curves/secp256k1';
import { createHash } from 'node:crypto';
import { prepareControlledProfessionalQrSession } from './controlled-qr-session.mjs';
const pub=n=>Buffer.from(secp256k1.getPublicKey(Buffer.from([...Buffer.alloc(31),n]),true));
const signer=pub(9),redeem=bitcoin.script.compile([bitcoin.script.number.encode(110),bitcoin.opcodes.OP_CHECKLOCKTIMEVERIFY,bitcoin.opcodes.OP_DROP,signer,bitcoin.opcodes.OP_CHECKSIG]);
const payment=bitcoin.payments.p2sh({redeem:{output:redeem},network:bitcoin.networks.regtest});
const handoff={version:1,network:'regtest',signerPubkeyHex:signer.toString('hex'),locktime:110,redeemScriptHex:redeem.toString('hex'),fundingAddress:payment.address};
const prev=new bitcoin.Transaction();prev.version=2;prev.addInput(Buffer.alloc(32,1),0);prev.addOutput(payment.output,100000);
const destination=bitcoin.payments.p2wpkh({pubkey:pub(10),network:bitcoin.networks.regtest});
const funding={fundingTxHex:prev.toHex(),vout:0,expectedTxid:prev.getId(),expectedSats:100000,masterFingerprintHex:'00000009',derivationPath:[0x80000054,0x80000000,0x80000000,1,10],destinationScriptHex:destination.output.toString('hex'),destinationSats:99000};
const intent={destinationScriptHex:funding.destinationScriptHex,destinationSats:99000,expectedTxid:funding.expectedTxid,vout:0,expectedSats:100000,locktime:110,signerPubkeyHex:handoff.signerPubkeyHex};
const session=prepareControlledProfessionalQrSession(handoff,funding,intent);
assert.throws(()=>session.exportQrFrames(),/Explicit approval required/);
const record=session.confirmation();
assert.equal(record.explicitlyApproved,false);
session.approve({confirmedDigest:record.psbtSha256,acknowledged:true});
const output=session.exportQrFrames({fragmentLength:120,frameCount:96});
assert.equal(output.signed,false);assert.equal(output.broadcast,false);
assert.equal(output.psbtSha256,record.psbtSha256);
assert.ok(output.frames.length===96);
assert.throws(()=>session.exportQrFrames(),/already consumed/);
const decoder=new URDecoder();
for(const frame of output.frames){decoder.receivePart(frame);if(decoder.isComplete())break;}
assert.equal(decoder.isSuccess(),true,'QR UR frames must decode');
const cbor=Buffer.from(decoder.resultUR().cbor);
assert.equal(cbor[0],0x59,'Expected two-byte CBOR bytestring length header');
const size=cbor.readUInt16BE(1),bytes=cbor.subarray(3);
assert.equal(bytes.length,size);
assert.equal(createHash('sha256').update(bytes).digest('hex'),record.psbtSha256,'Decoded QR must match approved PSBT exactly');
assert.equal(bitcoin.Psbt.fromBuffer(bytes).txOutputs[0].value,99000);
console.log('PASS: no QR before approval; one-time QR export; decoded crypto-psbt matches exact approved PSBT digest');
