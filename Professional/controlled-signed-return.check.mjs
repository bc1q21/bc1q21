import assert from 'node:assert/strict';
import bitcoin from 'bitcoinjs-lib';
import { secp256k1 } from '@noble/curves/secp256k1';
import { prepareControlledProfessionalQrSession } from './controlled-qr-session.mjs';
const secret=Buffer.alloc(32);secret[31]=9;
const pub=Buffer.from(secp256k1.getPublicKey(secret,true));
const redeem=bitcoin.script.compile([bitcoin.script.number.encode(110),bitcoin.opcodes.OP_CHECKLOCKTIMEVERIFY,bitcoin.opcodes.OP_DROP,pub,bitcoin.opcodes.OP_CHECKSIG]);
const payment=bitcoin.payments.p2sh({redeem:{output:redeem},network:bitcoin.networks.regtest});
const handoff={version:1,network:'regtest',signerPubkeyHex:pub.toString('hex'),locktime:110,redeemScriptHex:redeem.toString('hex'),fundingAddress:payment.address};
const prev=new bitcoin.Transaction();prev.version=2;prev.addInput(Buffer.alloc(32,1),0);prev.addOutput(payment.output,100000);
const dest=bitcoin.payments.p2wpkh({pubkey:Buffer.from(secp256k1.getPublicKey(Buffer.from([...Buffer.alloc(31),10]),true)),network:bitcoin.networks.regtest});
const funding={fundingTxHex:prev.toHex(),vout:0,expectedTxid:prev.getId(),expectedSats:100000,masterFingerprintHex:'00000009',derivationPath:[0x80000054,0x80000000,0x80000000,1,10],destinationScriptHex:dest.output.toString('hex'),destinationSats:99000};
const intent={destinationScriptHex:funding.destinationScriptHex,destinationSats:99000,expectedTxid:funding.expectedTxid,vout:0,expectedSats:100000,locktime:110,signerPubkeyHex:handoff.signerPubkeyHex};
const session=prepareControlledProfessionalQrSession(handoff,funding,intent);
assert.throws(()=>session.completeSignedReturn('garbage'),/Approved QR handoff required/);
const digest=session.confirmation().psbtSha256;
session.approve({confirmedDigest:digest,acknowledged:true});
session.exportQrFrames({fragmentLength:120,frameCount:96});
const unsigned=new bitcoin.Psbt({network:bitcoin.networks.regtest});
unsigned.setVersion(2);unsigned.setLocktime(110);
unsigned.addInput({hash:prev.getId(),index:0,sequence:0xfffffffe,nonWitnessUtxo:prev.toBuffer(),redeemScript:redeem,bip32Derivation:[{masterFingerprint:Buffer.from('00000009','hex'),path:"m/84'/0'/0'/1/10",pubkey:pub}]});
unsigned.addOutput({script:dest.output,value:99000});
const tx=bitcoin.Transaction.fromBuffer(unsigned.data.globalMap.unsignedTx.toBuffer());
const sighash=tx.hashForSignature(0,redeem,bitcoin.Transaction.SIGHASH_ALL);
const signature=bitcoin.script.signature.encode(Buffer.from(secp256k1.sign(sighash,secret,{lowS:true}).toCompactRawBytes()),bitcoin.Transaction.SIGHASH_ALL);
const signed=bitcoin.Psbt.fromBase64(unsigned.toBase64());
signed.updateInput(0,{partialSig:[{pubkey:pub,signature}]});
const result=session.completeSignedReturn(signed.toBase64());
assert.equal(result.independentFinalAuditPassed,true);
assert.equal(result.signatureCryptographicallyVerified,true);
assert.equal(result.finalized,true);
assert.equal(result.broadcast,false);
assert.equal(result.feeSats,1000);
assert.throws(()=>session.completeSignedReturn(signed.toBase64()),/already completed/);
const second=prepareControlledProfessionalQrSession(handoff,funding,intent);
second.approve({confirmedDigest:second.confirmation().psbtSha256,acknowledged:true});
second.exportQrFrames({fragmentLength:120,frameCount:96});
assert.throws(()=>second.completeSignedReturn(unsigned.toBase64()),/no signing material/);
assert.throws(()=>second.completeSignedReturn(signed.toBase64()),/attempt already consumed/,'Rejected return must close this session');
console.log('PASS: controlled QR session requires approved handoff and independently audited valid signature before finalization; no broadcast');
