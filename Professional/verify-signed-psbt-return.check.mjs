import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import bitcoin from 'bitcoinjs-lib';
import {verifyReturnedSignedProfessionalPsbt} from './verify-signed-psbt-return.mjs';
const prev=new bitcoin.Transaction();prev.addInput(Buffer.alloc(32,1),0);prev.addOutput(Buffer.from('0014'+'aa'.repeat(20),'hex'),100000);
const psbt=new bitcoin.Psbt({network:bitcoin.networks.regtest});
psbt.addInput({hash:prev.getId(),index:0,sequence:0xfffffffe,nonWitnessUtxo:prev.toBuffer(),redeemScript:Buffer.from('51','hex')});
psbt.addOutput({script:Buffer.from('0014'+'bb'.repeat(20),'hex'),value:99000});
const original=psbt.toBase64(),digest=createHash('sha256').update(Buffer.from(original,'base64')).digest('hex');
const signed=bitcoin.Psbt.fromBase64(original);
signed.updateInput(0,{partialSig:[{pubkey:Buffer.from('02'+'11'.repeat(32),'hex'),signature:Buffer.from('300602010102010101','hex')}]});
const returned=signed.toBase64();
const good=verifyReturnedSignedProfessionalPsbt(original,returned,digest);
assert.equal(good.transactionMatches,true);
assert.equal(good.signatureCryptographicallyVerified,false);
assert.throws(()=>verifyReturnedSignedProfessionalPsbt(original,original,digest),/no signing material/);
assert.throws(()=>verifyReturnedSignedProfessionalPsbt(original,returned,'00'.repeat(32)),/fingerprint mismatch/);
const altered=bitcoin.Psbt.fromBase64(original);altered.updateOutput(0,{script:Buffer.from('0014'+'cc'.repeat(20),'hex')});
altered.updateInput(0,{partialSig:[{pubkey:Buffer.from('02'+'11'.repeat(32),'hex'),signature:Buffer.from('300602010102010101','hex')}]});
assert.throws(()=>verifyReturnedSignedProfessionalPsbt(original,altered.toBase64(),digest),/transaction differs/);
const missing=bitcoin.Psbt.fromBase64(returned);missing.updateInput(0,{redeemScript:Buffer.from('52','hex')});
assert.throws(()=>verifyReturnedSignedProfessionalPsbt(original,missing.toBase64(),digest),/signing metadata differs/);
console.log('PASS: returned PSBT exact transaction, signing material, metadata and approved digest verified; cryptographic signature verification explicitly not claimed');
