import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const path=process.argv[2];
assert.ok(path,'Recorded Jade QR fixture path required');
const frames=readFileSync(path,'utf8').split(/\r?\n/).map(x=>x.trim()).filter(x=>/^ur:crypto-psbt\//i.test(x));
assert.ok(frames.length>=8);
const sandbox={Buffer:undefined,Uint8Array,TextEncoder,TextDecoder,console,setTimeout,clearTimeout,crypto:globalThis.crypto};
runInNewContext(readFileSync('professional-verifier.bundle.js','utf8'),sandbox,{timeout:15000});
const verify=sandbox.bc1q21ProfessionalVerify;
assert.equal(typeof verify,'function');
const result=await verify(frames);
assert.equal(result.signatureCryptographicallyVerified,true);
assert.equal(result.transactionMatches,true);
assert.equal(result.broadcast,false);
assert.equal(result.approvedPsbtSha256,'c5cfe8f53212d2aa3a4f2a747993f62a1284e5f973627b1c9410b1ad61659961');
await assert.rejects(()=>verify([]),/frame count/i);
await assert.rejects(()=>verify(frames.slice(0,2)),/incomplete/i);
await assert.rejects(()=>verify(['ur:bytes/1-1/invalid']),/invalid QR frame/i);
assert.equal((await verify([...frames].reverse())).signatureCryptographicallyVerified,true);
console.log('PASS: recorded physical Jade signed PSBT independently verified, no broadcast');
