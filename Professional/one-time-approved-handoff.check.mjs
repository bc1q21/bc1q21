import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import bitcoin from 'bitcoinjs-lib';
import { createOneTimeApprovedHandoff } from './one-time-approved-handoff.mjs';
const tx=new bitcoin.Transaction();tx.addInput(Buffer.alloc(32,1),0);tx.addOutput(Buffer.from('0014'+'aa'.repeat(20),'hex'),100000);
const psbt=new bitcoin.Psbt({network:bitcoin.networks.regtest});
psbt.addInput({hash:tx.getId(),index:0,sequence:0xfffffffe,nonWitnessUtxo:tx.toBuffer()});
psbt.addOutput({script:Buffer.from('0014'+'bb'.repeat(20),'hex'),value:99000});
const b64=psbt.toBase64(),hash=createHash('sha256').update(Buffer.from(b64,'base64')).digest('hex');
const record={network:'regtest',psbtSha256:hash,approvalVerified:true,signed:false,broadcast:false};
const release={network:'regtest',unsignedPsbtBase64:b64,signed:false,broadcast:false};
const make=()=>createOneTimeApprovedHandoff(record,{...release});
const a=make();
assert.equal(a.view().explicitlyApproved,false);
assert.throws(()=>a.handoff(),/Explicit approval required/);
assert.throws(()=>a.approve({confirmedDigest:'00'.repeat(32),acknowledged:true}),/fingerprint required/);
a.approve({confirmedDigest:hash,acknowledged:true});
assert.equal(a.view().explicitlyApproved,true);
a.invalidate();
assert.throws(()=>a.handoff(),/Explicit approval required/);
a.approve({confirmedDigest:hash,acknowledged:true});
const result=a.handoff();
assert.equal(result.unsignedPsbtBase64,b64);
assert.equal(a.view().approvalConsumed,true);
assert.equal(a.view().explicitlyApproved,false);
assert.throws(()=>a.handoff(),/already consumed/);
assert.throws(()=>a.approve({confirmedDigest:hash,acknowledged:true}),/already consumed/);
const altered=bitcoin.Psbt.fromBase64(b64);altered.addUnknownKeyValToOutput(0,{key:Buffer.from('fc01','hex'),value:Buffer.from('01','hex')});
const changed=altered.toBase64();assert.notEqual(changed,b64);
assert.throws(()=>createOneTimeApprovedHandoff(record,{...release,unsignedPsbtBase64:changed}),/does not match PSBT/);
const b=make();b.approve({confirmedDigest:hash,acknowledged:true});
assert.throws(()=>createOneTimeApprovedHandoff({...record,psbtSha256:'00'.repeat(32)},release),/does not match PSBT/);
console.log('PASS: exact PSBT approval is revoked, cannot be reused, and mismatched PSBT is rejected');
