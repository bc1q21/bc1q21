import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import bitcoin from 'bitcoinjs-lib';
import {secp256k1} from '@noble/curves/secp256k1';
import {finalizeVerifiedProfessionalRelease} from './finalize-verified-release.mjs';
const secret=Buffer.alloc(32);secret[31]=9;
const pub=Buffer.from(secp256k1.getPublicKey(secret,true));
const redeem=bitcoin.script.compile([bitcoin.script.number.encode(110),bitcoin.opcodes.OP_CHECKLOCKTIMEVERIFY,bitcoin.opcodes.OP_DROP,pub,bitcoin.opcodes.OP_CHECKSIG]);
const payment=bitcoin.payments.p2sh({redeem:{output:redeem},network:bitcoin.networks.regtest});
const prev=new bitcoin.Transaction();prev.version=2;prev.addInput(Buffer.alloc(32,1),0);prev.addOutput(payment.output,100000);
const psbt=new bitcoin.Psbt({network:bitcoin.networks.regtest});
psbt.setVersion(2);psbt.setLocktime(110);
psbt.addInput({hash:prev.getId(),index:0,sequence:0xfffffffe,nonWitnessUtxo:prev.toBuffer(),redeemScript:redeem});
psbt.addOutput({script:Buffer.from('0014'+'bb'.repeat(20),'hex'),value:99000});
const original=psbt.toBase64(),digest=createHash('sha256').update(Buffer.from(original,'base64')).digest('hex');
const tx=bitcoin.Transaction.fromBuffer(psbt.data.globalMap.unsignedTx.toBuffer());
const hash=tx.hashForSignature(0,redeem,bitcoin.Transaction.SIGHASH_ALL);
const signature=bitcoin.script.signature.encode(Buffer.from(secp256k1.sign(hash,secret,{lowS:true}).toCompactRawBytes()),bitcoin.Transaction.SIGHASH_ALL);
const signed=bitcoin.Psbt.fromBase64(original);
signed.updateInput(0,{partialSig:[{pubkey:pub,signature}]});
const finalized=finalizeVerifiedProfessionalRelease(original,signed.toBase64(),digest);
assert.equal(finalized.signatureCryptographicallyVerified,true);
assert.equal(finalized.finalized,true);assert.equal(finalized.broadcast,false);
const extracted=bitcoin.Transaction.fromHex(finalized.rawTransactionHex);
assert.equal(extracted.getId(),finalized.txid);
assert.equal(extracted.locktime,110);
assert.equal(extracted.outs[0].value,99000);
const chunks=bitcoin.script.decompile(extracted.ins[0].script);
assert.equal(chunks.length,2);
assert.deepEqual(chunks[0],signature);assert.deepEqual(chunks[1],redeem);
assert.throws(()=>finalizeVerifiedProfessionalRelease(original,original,digest),/no signing material/);
assert.throws(()=>finalizeVerifiedProfessionalRelease(original,signed.toBase64(),'00'.repeat(32)),/fingerprint mismatch/);
const bad=bitcoin.Psbt.fromBase64(original);
const badHash=Buffer.from(hash);badHash[0]^=1;
bad.updateInput(0,{partialSig:[{pubkey:pub,signature:bitcoin.script.signature.encode(Buffer.from(secp256k1.sign(badHash,secret,{lowS:true}).toCompactRawBytes()),bitcoin.Transaction.SIGHASH_ALL)}]});
assert.throws(()=>finalizeVerifiedProfessionalRelease(original,bad.toBase64(),digest),/Invalid Bitcoin transaction signature/);
console.log('PASS: independently verified signed CLTV PSBT finalizes into correct raw regtest transaction; invalid signatures rejected; never broadcasts');
