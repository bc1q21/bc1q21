import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import bitcoin from 'bitcoinjs-lib';
import {secp256k1} from '@noble/curves/secp256k1';
import {finalizeVerifiedProfessionalRelease} from './finalize-verified-release.mjs';
import {auditFinalizedProfessionalTransaction} from './audit-finalized-transaction.mjs';
const key=Buffer.alloc(32);key[31]=9;
const pub=Buffer.from(secp256k1.getPublicKey(key,true));
const redeem=bitcoin.script.compile([bitcoin.script.number.encode(110),bitcoin.opcodes.OP_CHECKLOCKTIMEVERIFY,bitcoin.opcodes.OP_DROP,pub,bitcoin.opcodes.OP_CHECKSIG]);
const payment=bitcoin.payments.p2sh({redeem:{output:redeem},network:bitcoin.networks.regtest});
const prev=new bitcoin.Transaction();prev.version=2;prev.addInput(Buffer.alloc(32,1),0);prev.addOutput(payment.output,100000);
const dest=Buffer.from('0014'+'bb'.repeat(20),'hex');
const psbt=new bitcoin.Psbt({network:bitcoin.networks.regtest});
psbt.setVersion(2);psbt.setLocktime(110);
psbt.addInput({hash:prev.getId(),index:0,sequence:0xfffffffe,nonWitnessUtxo:prev.toBuffer(),redeemScript:redeem});
psbt.addOutput({script:dest,value:99000});
const unsigned=psbt.toBase64(),digest=createHash('sha256').update(Buffer.from(unsigned,'base64')).digest('hex');
const tx=bitcoin.Transaction.fromBuffer(psbt.data.globalMap.unsignedTx.toBuffer());
const sighash=tx.hashForSignature(0,redeem,bitcoin.Transaction.SIGHASH_ALL);
const signature=bitcoin.script.signature.encode(Buffer.from(secp256k1.sign(sighash,key,{lowS:true}).toCompactRawBytes()),bitcoin.Transaction.SIGHASH_ALL);
const signed=bitcoin.Psbt.fromBase64(unsigned);
signed.updateInput(0,{partialSig:[{pubkey:pub,signature}]});
const final=finalizeVerifiedProfessionalRelease(unsigned,signed.toBase64(),digest);
const approved={fundingTxid:prev.getId(),fundingVout:0,inputSats:100000,destinationScriptHex:dest.toString('hex'),payoutSats:99000,locktime:110,signerPubkeyHex:pub.toString('hex'),redeemScriptHex:redeem.toString('hex')};
const report=auditFinalizedProfessionalTransaction(final.rawTransactionHex,approved);
assert.equal(report.txid,final.txid);assert.equal(report.feeSats,1000);
assert.equal(report.signatureCryptographicallyVerified,true);
assert.equal(report.finalTransactionVerified,true);assert.equal(report.broadcast,false);
assert.throws(()=>auditFinalizedProfessionalTransaction(final.rawTransactionHex,{...approved,payoutSats:98000}),/Final destination or payout mismatch/);
assert.throws(()=>auditFinalizedProfessionalTransaction(final.rawTransactionHex,{...approved,locktime:111}),/Final CLTV locktime or sequence mismatch/);
assert.throws(()=>auditFinalizedProfessionalTransaction(final.rawTransactionHex,{...approved,signerPubkeyHex:'02'+'11'.repeat(32)}),/Final signer or CLTV script mismatch/);
const altered=bitcoin.Transaction.fromHex(final.rawTransactionHex);
altered.outs[0].value=98000;
assert.throws(()=>auditFinalizedProfessionalTransaction(altered.toHex(),approved),/Final destination or payout mismatch/);
console.log('PASS: independently audited final regtest transaction signature, destination, amount, fee and CLTV; tampering rejected');
