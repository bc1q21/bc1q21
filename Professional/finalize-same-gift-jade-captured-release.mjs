import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {URDecoder} from '@ngraveio/bc-ur';
import cbor from 'cbor';
import bitcoin from 'bitcoinjs-lib';
import {auditSameGiftUnsignedHandoff} from './audit-same-gift-unsigned-handoff.mjs';
import {verifyReturnedSignedProfessionalPsbt} from './verify-signed-psbt-return.mjs';
const [framesPath,handoffPath,rawPath]=process.argv.slice(2);
assert.ok(framesPath&&handoffPath&&rawPath);
const h=JSON.parse(readFileSync(handoffPath,'utf8'));
auditSameGiftUnsignedHandoff(h);
const dec=new URDecoder();
for(const s of readFileSync(framesPath,'utf8').split(/\r?\n/).filter(x=>/^ur:crypto-psbt\//i.test(x)))dec.receivePart(s.trim());
assert.ok(dec.isComplete()&&dec.isSuccess());
const signed=bitcoin.Psbt.fromBuffer(Buffer.from(cbor.decodeFirstSync(Buffer.from(dec.resultUR().cbor))),{network:bitcoin.networks.regtest});
verifyReturnedSignedProfessionalPsbt(h.unsignedPsbtBase64,signed.toBase64(),h.psbtSha256);
const i=signed.data.inputs[0];
assert.equal(i.partialSig?.length,1);
const redeem=Buffer.from(i.redeemScript);
const sig=Buffer.from(i.partialSig[0].signature);
assert.equal(sig.at(-1),bitcoin.Transaction.SIGHASH_ALL);
assert.equal(Buffer.from(i.partialSig[0].pubkey).toString('hex'),h.signerPubkeyHex);
signed.finalizeInput(0,()=>({finalScriptSig:bitcoin.script.compile([sig,redeem])}));
const tx=signed.extractTransaction();
assert.equal(tx.ins.length,1);assert.equal(tx.outs.length,1);
assert.equal(tx.getId().length,64);
assert.equal(tx.locktime,h.locktime);
assert.equal(tx.outs[0].value,h.payoutSats);
assert.equal(Buffer.from(tx.outs[0].script).toString('hex'),h.destinationScriptHex);
assert.equal(Buffer.from(tx.ins[0].hash).reverse().toString('hex'),h.fundingTxid);
assert.equal(tx.ins[0].index,h.vout);
writeFileSync(rawPath,tx.toHex()+'\n',{flag:'wx',mode:0o600});
console.log('PASS_SAME_GIFT_SIGNED_RELEASE_FINALIZED',JSON.stringify({txid:tx.getId(),outpoint:h.fundingTxid+':'+h.vout,feeSats:h.feeSats,payoutSats:h.payoutSats,broadcast:false}));
